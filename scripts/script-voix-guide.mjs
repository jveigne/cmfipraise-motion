/**
 * Génère les scripts de narration minutés de la vidéo « Guide » depuis le découpage du code
 * (src/guide/frise.ts et src/guide/textes.ts) : docs/script-voix-guide-fr.md et -en.md.
 * Usage : node scripts/script-voix-guide.mjs — à relancer après toute retouche d'un texte ou d'une
 * durée (les timecodes suivent automatiquement).
 */
import path from 'node:path';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

const racine = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const tmp = fs.mkdtempSync(path.join(process.env.TMPDIR ?? '/tmp', 'frise-'));
execFileSync('npx', ['tsc', 'src/guide/frise.ts', '--outDir', tmp, '--module', 'commonjs', '--target', 'es2020', '--skipLibCheck'], { cwd: racine, stdio: 'ignore' });
const req = createRequire(import.meta.url);
const { FRISE, DUREE_GUIDE, IPS, timecode } = req(path.join(tmp, 'guide', 'frise.js'));
const { TEXTES_GUIDE, motsVoix } = req(path.join(tmp, 'guide', 'textes.js'));

const L = {
  fr: {
    titre: 'Script de narration — vidéo « Guide » (GuideFR)',
    intro: (d) => [
      `Durée de la vidéo : **${timecode(d)}** (${d} images à ${IPS} i/s). Une ligne par plan ; le texte à dire tient dans la durée du plan au rythme parlé d’environ 2,5 mots par seconde (colonne « mots / place »).`,
      '',
      'Généré par `node scripts/script-voix-guide.mjs` depuis `src/guide/textes.ts` et `src/guide/frise.ts` : ne pas modifier ce fichier à la main, il serait écrasé.',
      '',
      '**Enregistrer sa voix.** Lire chaque ligne en commençant à son timecode de début (la colonne « À l’écran » rappelle ce qui est affiché). Laisser un court silence en début de plan : le texte à l’écran apparaît en ≈ 0,5 s. Exporter **un seul fichier** de la durée de la vidéo (MP3 ou WAV, 48 kHz conseillé), calé sur 0:00.0, dans `public/audio/` (ex. `public/audio/voix-guide-fr.mp3`), puis rendre :',
      '',
      '```bash',
      'npx remotion render GuideFR out/guide-fr-voix.mp4 --props=\'{"voix":"audio/voix-guide-fr.mp3"}\'',
      '```',
      '',
      'La musique baisse alors nettement sous la voix ; ajouter `"musique":false` aux props pour la couper.',
      '',
      '| # | Plan | Début → fin | Durée | À l’écran | Texte à dire | mots / place |',
      '|---|---|---|---|---|---|---|',
    ],
  },
  en: {
    titre: 'Narration script — “Guide” video (GuideEN)',
    intro: (d) => [
      `Video length: **${timecode(d)}** (${d} frames at ${IPS} fps). One line per shot; the narration fits the shot at a spoken pace of about 2.5 words per second (column “words / room”).`,
      '',
      'Generated by `node scripts/script-voix-guide.mjs` from `src/guide/textes.ts` and `src/guide/frise.ts`: do not edit by hand, it would be overwritten.',
      '',
      '**Recording.** Start each line at its start timecode (the “On screen” column recalls what is shown). Leave a short silence at the start of each shot: the on-screen text fades in in about 0.5 s. Export **a single file** as long as the video (MP3 or WAV, 48 kHz recommended), aligned on 0:00.0, into `public/audio/` (e.g. `public/audio/voix-guide-en.mp3`), then render:',
      '',
      '```bash',
      'npx remotion render GuideEN out/guide-en-voix.mp4 --props=\'{"voix":"audio/voix-guide-en.mp3"}\'',
      '```',
      '',
      'The music then drops well below the voice; add `"musique":false` to the props to mute it.',
      '',
      '| # | Shot | Start → end | Length | On screen | Narration | words / room |',
      '|---|---|---|---|---|---|---|',
    ],
  },
};

for (const langue of ['fr', 'en']) {
  const t = TEXTES_GUIDE[langue];
  const lignes = [`# ${L[langue].titre}`, '', ...L[langue].intro(DUREE_GUIDE)];
  FRISE.forEach((e, i) => {
    const p = t.plans[e.id];
    const ecran = [p.titre, ...(Array.isArray(p.texte) ? p.texte : [p.texte])].filter(Boolean).join(' — ').replace(/\*/g, '').replace(/\|/g, '/');
    const place = Math.floor((e.duree / IPS - 0.6) * 2.5);
    lignes.push(
      `| ${i + 1} | ${e.id} | ${timecode(e.debut)} → ${timecode(e.debut + e.duree)} | ${langue === 'fr' ? (e.duree / IPS).toFixed(1).replace('.', ',') : (e.duree / IPS).toFixed(1)} s | ${ecran} | ${p.voix.replace(/\|/g, '/')} | ${motsVoix(p)} / ${place} |`,
    );
  });
  lignes.push('');
  fs.writeFileSync(path.join(racine, 'docs', `script-voix-guide-${langue}.md`), lignes.join('\n'));
  console.log(`docs/script-voix-guide-${langue}.md`);
}
